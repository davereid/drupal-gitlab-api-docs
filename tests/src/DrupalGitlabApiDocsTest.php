<?php

declare(strict_types=1);

namespace DrupalGitlabApiDocs\Tests;

use PHPUnit\Framework\Attributes\CoversNothing;
use PHPUnit\Framework\TestCase;

/**
 * Runs bin/drupal-gitlab-api-docs on the example module in tests/fixtures.
 */
#[CoversNothing]
final class DrupalGitlabApiDocsTest extends TestCase {

  /**
   * A copy of the example module, in a temporary directory.
   */
  private string $module;

  /**
   * {@inheritdoc}
   */
  protected function setUp(): void {
    parent::setUp();
    $this->module = sys_get_temp_dir() . '/drupal-gitlab-api-docs-' . bin2hex(random_bytes(4));
    $this->copyDirectory(__DIR__ . '/../fixtures/example', $this->module);
  }

  /**
   * {@inheritdoc}
   */
  protected function tearDown(): void {
    $this->deleteDirectory($this->module);
    parent::tearDown();
  }

  /**
   * Tests the pages generated for a module with hooks and events.
   */
  public function testGenerateWithHooksAndEvents(): void {
    $this->generate('-d src -d example.api.php');

    $index = $this->readPage('api/index.md');
    $this->assertStringStartsWith("# API reference\n", $index);
    $this->assertStringContainsString("#### Hooks\n\n| Hook ", $index);
    $this->assertStringContainsString('(./../hooks.md#hook_example_type_alter)', $index);
    $this->assertStringContainsString('[`ExampleEvents`](./../events.md)', $index);
    $this->assertStringStartsWith("# ExampleService\n", $this->readPage('api/ExampleService.md'));

    $hooks = $this->readPage('hooks.md');
    $this->assertStringStartsWith("# Hooks\n\n<!-- Generated by fix-api-docs.php: changes are lost on the next run. -->\n\n## hook_example_TYPE_alter()\n", $hooks);
    $this->assertStringContainsString('Alters the example data.', $hooks);

    $this->assertSame(<<<'MD'
      # Events

      <!-- Generated by fix-api-docs.php: changes are lost on the next run. -->

      ## example.save

      Occurs when an example is saved.

      - See `\Drupal\example\ExampleService`

      * Constant: `\Drupal\example\ExampleEvents::SAVE`

      MD, $this->readPage('events.md'));

    $this->assertFileDoesNotExist("$this->module/docs/api/ExampleEvents.md");
    $this->assertDirectoryDoesNotExist("$this->module/docs/api/functions");
    $this->assertDirectoryDoesNotExist("$this->module/docs/api/classes");
  }

  /**
   * Tests that a module without hooks or events gets neither page.
   */
  public function testGenerateWithoutHooksOrEvents(): void {
    $this->generate('-d src -d example.api.php');
    unlink("$this->module/example.api.php");
    unlink("$this->module/src/ExampleEvents.php");
    $this->generate('-d src');

    $this->assertStringStartsWith("# ExampleService\n", $this->readPage('api/ExampleService.md'));
    // The pages from the first run are removed.
    $this->assertFileDoesNotExist("$this->module/docs/hooks.md");
    $this->assertFileDoesNotExist("$this->module/docs/events.md");
  }

  /**
   * Tests that a hooks.md page someone wrote is kept.
   */
  public function testGenerateKeepsWrittenHooksPage(): void {
    mkdir("$this->module/docs");
    file_put_contents("$this->module/docs/hooks.md", "# Hooks\n");
    $this->generate('-d src -d example.api.php', 1);

    $this->assertStringEqualsFile("$this->module/docs/hooks.md", "# Hooks\n");
  }

  /**
   * Tests that pages left from an earlier run are removed.
   */
  public function testGenerateRemovesOldPages(): void {
    mkdir("$this->module/docs/api", 0777, TRUE);
    touch("$this->module/docs/api/Removed.md");
    $this->generate('-d src');

    $this->assertFileDoesNotExist("$this->module/docs/api/Removed.md");
  }

  /**
   * Runs bin/drupal-gitlab-api-docs in the example module.
   */
  private function generate(string $arguments, int $expectedCode = 0): void {
    $bin = escapeshellarg(dirname(__DIR__, 2) . '/bin/drupal-gitlab-api-docs');
    exec('cd ' . escapeshellarg($this->module) . ' && ' . escapeshellarg(PHP_BINARY) . " $bin $arguments --cache-folder=.phpdoc 2>&1", $output, $code);
    $this->assertSame($expectedCode, $code, implode("\n", $output));
  }

  /**
   * Reads a generated page, by its path in docs.
   */
  private function readPage(string $path): string {
    $this->assertFileExists("$this->module/docs/$path");
    return file_get_contents("$this->module/docs/$path");
  }

  /**
   * Copies a directory recursively.
   */
  private function copyDirectory(string $source, string $destination): void {
    mkdir($destination, 0777, TRUE);
    foreach (new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($source, \FilesystemIterator::SKIP_DOTS), \RecursiveIteratorIterator::SELF_FIRST) as $file) {
      $target = $destination . substr($file->getPathname(), strlen($source));
      $file->isDir() ? mkdir($target) : copy($file->getPathname(), $target);
    }
  }

  /**
   * Deletes a directory recursively.
   */
  private function deleteDirectory(string $directory): void {
    foreach (new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($directory, \FilesystemIterator::SKIP_DOTS), \RecursiveIteratorIterator::CHILD_FIRST) as $file) {
      $file->isDir() ? rmdir($file->getPathname()) : unlink($file->getPathname());
    }
    rmdir($directory);
  }

}
